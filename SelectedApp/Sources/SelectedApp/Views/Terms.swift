import Foundation

/// 全 App **术语的唯一来源** —— 与 `Tokens.swift`（颜色唯一来源）同一个思路：
/// 颜色散写会"同一语义两种色"，术语散写会"同一概念不同页面叫法不同"，这里固化规范写法。
///
/// ## 为什么不把中文文案都搬进来
/// 这里只放**「同一概念可能被叫成不同名字」**的那些。
/// 其余文案（按钮标题、说明文字）就写在用到它的地方。判据是：
/// **这个概念会不会在两个以上的地方被指称？** 会 ⇒ 进这里。
enum Terms {

    // MARK: 指数

    /// 指数显示名的**规范写法**。
    ///
    /// ⚠ 只管「上证系列」这一个。其余指数（沪深300 / 中证500 / 上证50 / 深证成指…）
    ///   全仓写法已统一，不必进这个表（`SettingsClassifySection` 的「上证50」是**指数名**，
    ///   不是「上证指数」的简称，两者指的不是一回事，别混）。
    static let shangHaiIndex = "上证指数"

    /// 简称是否允许 —— 目前**不允许**。
    /// 保留这个函数是为了让「以后想统一加简称」时有个明确的决策点。
    static func indexName(_ full: String) -> String { full }

    // MARK: 按钮动作

    /// 「回到最新位置」按钮的规范文案。
    ///
    /// ⚠ 用「回到最新」而不是「回最新」：完整动宾结构在按钮里读起来更自然。
    static let backToLatest = "回到最新"

    // MARK: 指标（三个"率"是不同的量，**刻意不统一**，理由见各成员注释）

    /// 四层胜率 —— 选股**质量**指标（`reviews.four_layer_json` 的四层判定）。
    /// 本项目的核心指标，**不要**改成「命中率」。
    static let winRateFourLayer = "四层胜率"

    /// 窗口命中率 —— **准确度**指标（`acc.windowHitRate`，预判方向是否命中）。
    /// ⚠ 与 `winRateFourLayer` 是**两个不同的指标**，**不要**为了"统一术语"把两者合并。
    static let windowHitRate = "窗口命中率"

    /// 区间预测的滚动回测命中率（`ForecastSheet`，衡量次日区间估计方法的历史表现）。
    /// ⚠ 同上，**第三个**不同的量。
    static let forecastBacktestHitRate = "逐日滚动回测命中率"
}
